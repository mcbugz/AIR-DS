/**
 * Platform emitters (Mandate v2 / M5 — portability proof).
 *
 * Two additional render targets derived from the SAME resolved token graph
 * that produces dist/css/tokens.css, dist/index.js|d.ts, and the registry:
 *
 *   dist/wc/tokens.css           custom properties scoped for Shadow-DOM
 *                                consumption (`:host, :root`)
 *   dist/react-native/tokens.ts  typed React-Native style object (dp numbers,
 *                                color strings, RN shadow/elevation mapping)
 *
 * Both are brand-aware for free: they receive the already-resolved
 * PublicToken list, so `--brand` flows through unchanged. This module is
 * ADDITIVE — it never touches the legacy emitters, and the byte-identity
 * test (test/platforms.test.ts) proves the legacy outputs are unchanged.
 */

import type { PublicToken } from "./build.ts";

