/**
 * Machine-readable record of every platform the token graph is emitted for.
 * A SEPARATE registry file so registries/tokens-index.json stays byte-stable:
 * token entries are platform-independent; emission targets are metadata.
 */
export function buildPlatformsManifest(brandLabel: string, tokenCount: number): string {
  const manifest = {
    $description:
      "GENERATED platform-emission manifest. Every render target the resolved token graph is compiled to, from the same DTCG source and the same deterministic resolver. Paths are relative to the build's dist directory (packages/tokens/dist for the workspace build). tokens-index.json remains the single closed-world token contract; this file only enumerates emission targets. An emitted platform not listed here does not exist.",
    brand: brandLabel,
    tokenCount,
    platforms: [
      {
        platform: "web",
        output: "css/tokens.css",
        format: "css-custom-properties",
        scope: ":root",
        lossless: true,
        notes: "Canonical web build; also mirrored to dist/index.js + index.d.ts (typed closed-world map).",
      },
      {
        platform: "web-components",
        output: "wc/tokens.css",
        format: "css-custom-properties",
        scope: ":host, :root",
        lossless: true,
        notes:
          "Identical custom-property vocabulary, scoped for Shadow-DOM adoption (adoptedStyleSheets / constructable stylesheet; :root fallback for document-level linking).",
      },
      {
        platform: "react-native",
        output: "react-native/tokens.ts",
        format: "typescript-object",
        scope: null,
        lossless: false,
        lossiness: RN_LOSSINESS,
        notes: "Numeric dp values, color strings, RN shadow/elevation conventions; see lossiness.",
      },
    ],
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}
