/**
 * Same custom-property vocabulary as dist/css/tokens.css, re-scoped for
 * Shadow DOM. `:host` makes the variables resolve when the sheet is adopted
 * INTO a shadow root (adoptedStyleSheets / a <style> inside the root), which
 * is required when the host page's `:root` is not under the consumer's
 * control (embedded widgets, nested shadow trees). `:root` is the documented
 * fallback: linking this file at document level works too, because custom
 * properties inherit across shadow boundaries.
 */
export function emitWcCss(tokens: readonly PublicToken[], brandLabel: string): string {
  const lines: string[] = [
    `/* GENERATED by @ds/tokens — do not edit. Brand: ${brandLabel} */`,
    `/* Shadow-DOM build: identical custom properties to css/tokens.css, scoped \`:host, :root\`. */`,
    `/* \`:host\` — adopt this sheet into a shadow root via adoptedStyleSheets (constructable`,
    `   stylesheet) or a <style> fallback; variables then resolve inside that root even when`,
    `   the document's :root is not yours. */`,
    `/* \`:root\` fallback — linking this file at document level also works: custom properties`,
    `   inherit across shadow boundaries, so light-DOM and shadow-DOM consumers both resolve. */`,
    ":host, :root {",
  ];
  for (const tier of ["semantic", "component"] as const) {
    lines.push(`  /* ${tier} tier */`);
    for (const t of tokens) {
      if (t.tier !== tier) continue;
      lines.push(`  ${t.cssVar}: ${String(t.value)};`);
    }
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

