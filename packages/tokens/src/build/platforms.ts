/** RN shadow object shape emitted for DTCG `shadow` tokens. */
export interface RnShadowValue {
  shadowColor: string;
  shadowOffset: { width: number; height: number };
  shadowRadius: number;
  shadowOpacity: number;
  elevation: number;
}

type RnValue = string | number | undefined | readonly number[] | RnShadowValue;

interface Converted {
  value: RnValue;
  /** Emitted as a trailing `// note:` comment on the token's line. */
  note?: string;
}

const GENERIC_FAMILIES = new Set([
  "system-ui",
  "-apple-system",
  "ui-monospace",
  "ui-sans-serif",
  "ui-serif",
  "ui-rounded",
  "sans-serif",
  "serif",
  "monospace",
  "cursive",
  "fantasy",
]);

function parseNumber(s: string, ctx: string): number {
  const n = Number(s);
  if (!Number.isFinite(n)) throw new Error(`RN emit: non-numeric "${s}" in ${ctx}`);
  return n;
}

function convertDimension(name: string, value: string): Converted {
  const px = /^(-?\d+(?:\.\d+)?)px$/.exec(value);
  if (px) return { value: parseNumber(px[1] as string, name) };
  const rem = /^(-?\d+(?:\.\d+)?)rem$/.exec(value);
  if (rem) return { value: parseNumber(rem[1] as string, name) * 16, note: "rem -> dp at 16px root" };
  const calc = /^calc\((-?\d+(?:\.\d+)?)px \* (-?\d+(?:\.\d+)?)\)$/.exec(value);
  if (calc) return { value: parseNumber(calc[1] as string, name) * parseNumber(calc[2] as string, name) };
  if (/^-?\d+(?:\.\d+)?%$/.test(value)) {
    return { value, note: "percentage passthrough — see header note 6" };
  }
  throw new Error(`RN emit: token "${name}" has unconvertible dimension "${value}"`);
}

function convertDuration(name: string, value: string): Converted {
  const ms = /^(\d+(?:\.\d+)?)ms$/.exec(value);
  if (ms) return { value: parseNumber(ms[1] as string, name) };
  const s = /^(\d+(?:\.\d+)?)s$/.exec(value);
  if (s) return { value: parseNumber(s[1] as string, name) * 1000 };
  throw new Error(`RN emit: token "${name}" has unconvertible duration "${value}"`);
}

function convertFontFamily(value: string): Converted {
  const first = (value.split(",")[0] ?? "").trim().replace(/^['"]|['"]$/g, "");
  if (first === "" || GENERIC_FAMILIES.has(first)) {
    return { value: undefined, note: "system stack -> platform default font (omit fontFamily)" };
  }
  return { value: first, note: "first family of the CSS stack; fallbacks dropped" };
}

function convertCubicBezier(name: string, value: string): Converted {
  const m = /^cubic-bezier\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)$/.exec(value);
  if (!m) throw new Error(`RN emit: token "${name}" has unconvertible easing "${value}"`);
  return {
    value: [1, 2, 3, 4].map((i) => parseNumber(m[i] as string, name)),
    note: "feed to Easing.bezier(x1, y1, x2, y2)",
  };
}

interface ParsedShadowColor {
  hex: string;
  opacity: number;
}

function parseShadowColor(raw: string, name: string): ParsedShadowColor {
  const hex6 = /^#([0-9a-fA-F]{6})$/.exec(raw);
  if (hex6) return { hex: `#${(hex6[1] as string).toLowerCase()}`, opacity: 1 };
  const rgb = /^rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)$/.exec(raw);
  if (rgb) {
    const to2 = (v: string): string => parseNumber(v, name).toString(16).padStart(2, "0");
    const alphaRaw = rgb[4];
    const opacity =
      alphaRaw === undefined
        ? 1
        : alphaRaw.endsWith("%")
          ? parseNumber(alphaRaw.slice(0, -1), name) / 100
          : parseNumber(alphaRaw, name);
    return { hex: `#${to2(rgb[1] as string)}${to2(rgb[2] as string)}${to2(rgb[3] as string)}`, opacity };
  }
  throw new Error(`RN emit: token "${name}" has unconvertible shadow color "${raw}"`);
}

function convertShadow(name: string, value: string): Converted {
  // Layers are comma-separated; no color used in shadows contains a top-level
  // comma (hex or space-syntax rgb), but split defensively outside parens.
  const layers: string[] = [];
  let depth = 0;
  let cur = "";
  for (const ch of value) {
    if (ch === "(") depth += 1;
    if (ch === ")") depth -= 1;
    if (ch === "," && depth === 0) {
      layers.push(cur.trim());
      cur = "";
    } else {
      cur += ch;
    }
  }
  if (cur.trim() !== "") layers.push(cur.trim());
  if (layers.length === 0) throw new Error(`RN emit: token "${name}" has empty shadow value`);

  const first = layers[0] as string;
  const colorMatch = /(#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)|hsla?\([^)]*\))/.exec(first);
  if (!colorMatch) throw new Error(`RN emit: token "${name}" shadow layer has no color: "${first}"`);
  const color = parseShadowColor(colorMatch[1] as string, name);
  const lengths = first
    .replace(colorMatch[1] as string, " ")
    .trim()
    .split(/\s+/)
    .filter((p) => p !== "")
    .map((p) => {
      const m = /^(-?\d+(?:\.\d+)?)(px)?$/.exec(p);
      if (!m) throw new Error(`RN emit: token "${name}" shadow length "${p}" is not a px value`);
      return parseNumber(m[1] as string, name);
    });
  if (lengths.length < 2) throw new Error(`RN emit: token "${name}" shadow needs at least x and y offsets`);
  const [x = 0, y = 0, blur = 0, spread = 0] = lengths;

  const shadow: RnShadowValue = {
    shadowColor: color.hex,
    shadowOffset: { width: x, height: y },
    shadowRadius: blur / 2,
    shadowOpacity: color.opacity,
    elevation: Math.max(0, Math.round(y)),
  };
  const notes: string[] = [];
  if (layers.length > 1) notes.push(`first of ${layers.length} CSS layers; the rest are dropped`);
  if (spread !== 0) notes.push(`CSS spread ${spread}px dropped (no RN equivalent${blur === 0 ? "; render as a border" : ""})`);
  return notes.length > 0 ? { value: shadow, note: notes.join("; ") } : { value: shadow };
}

function convertToken(t: PublicToken): Converted {
  switch (t.type) {
    case "color":
      return { value: String(t.value) };
    case "dimension":
      return convertDimension(t.name, String(t.value));
    case "duration":
      return convertDuration(t.name, String(t.value));
    case "number": {
      if (typeof t.value === "number") return { value: t.value };
      const pct = /^(-?\d+(?:\.\d+)?)%$/.exec(String(t.value));
      if (pct) {
        return {
          value: parseNumber(pct[1] as string, t.name) / 100,
          note: `${String(t.value)} -> unit scale (RN opacity is 0-1)`,
        };
      }
      return { value: parseNumber(String(t.value), t.name) };
    }
    case "fontWeight":
      // RN fontWeight is the string form ("400" | "500" | ...).
      return { value: String(t.value) };
    case "fontFamily":
      return convertFontFamily(String(t.value));
    case "cubicBezier":
      return convertCubicBezier(t.name, String(t.value));
    case "shadow":
      return convertShadow(t.name, String(t.value));
    default:
      throw new Error(`RN emit: token "${t.name}" has unmapped $type "${t.type}"`);
  }
}

/* ---------- nested object serialization ---------- */

interface TreeGroup {
  kind: "group";
  children: Map<string, TreeNode>;
}

interface TreeLeaf {
  kind: "leaf";
  converted: Converted;
}

type TreeNode = TreeGroup | TreeLeaf;

const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function keyLiteral(key: string): string {
  return IDENT_RE.test(key) ? key : JSON.stringify(key);
}

function valueLiteral(v: RnValue): string {
  if (v === undefined) return "undefined";
  if (typeof v === "number" || typeof v === "string") return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.join(", ")}] as const`;
  const s = v as RnShadowValue;
  return (
    `{ shadowColor: ${JSON.stringify(s.shadowColor)}, ` +
    `shadowOffset: { width: ${s.shadowOffset.width}, height: ${s.shadowOffset.height} }, ` +
    `shadowRadius: ${s.shadowRadius}, shadowOpacity: ${s.shadowOpacity}, elevation: ${s.elevation} }`
  );
}

function serializeGroup(group: TreeGroup, indent: string, out: string[]): void {
  for (const [key, node] of group.children) {
    if (node.kind === "leaf") {
      const note = node.converted.note === undefined ? "" : ` // note: ${node.converted.note}`;
      out.push(`${indent}${keyLiteral(key)}: ${valueLiteral(node.converted.value)},${note}`);
    } else {
      out.push(`${indent}${keyLiteral(key)}: {`);
      serializeGroup(node, `${indent}  `, out);
      out.push(`${indent}},`);
    }
  }
}

/**
 * Emit dist/react-native/tokens.ts: the resolved token graph as one nested,
 * `as const`-typed object keyed by DTCG path segments. Deterministic: tokens
 * are inserted in sorted-name order; conversions are pure functions of the
 * resolved value.
 */
export function emitReactNativeTs(tokens: readonly PublicToken[], brandLabel: string): string {
  const root: TreeGroup = { kind: "group", children: new Map() };
  const sorted = [...tokens].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const t of sorted) {
    const segments = t.name.split(".");
    let node: TreeGroup = root;
    segments.forEach((seg, i) => {
      if (i === segments.length - 1) {
        if (node.children.has(seg)) {
          throw new Error(`RN emit: path collision at "${t.name}" (leaf vs group)`);
        }
        node.children.set(seg, { kind: "leaf", converted: convertToken(t) });
        return;
      }
      const existing = node.children.get(seg);
      if (existing === undefined) {
        const next: TreeGroup = { kind: "group", children: new Map() };
        node.children.set(seg, next);
        node = next;
      } else if (existing.kind === "group") {
        node = existing;
      } else {
        throw new Error(`RN emit: path collision at "${t.name}" (group vs leaf)`);
      }
    });
  }

  const body: string[] = [];
  serializeGroup(root, "  ", body);

  return [
    "// GENERATED by @ds/tokens — do not edit.",
    `// Brand: ${brandLabel}`,
    "//",
    "// React Native token build: the same resolved DTCG graph as css/tokens.css,",
    "// emitted as a typed object. Dimensions are density-independent-pixel numbers,",
    "// colors are hex strings, shadows follow RN shadow*/elevation conventions.",
    "//",
    "// HONEST LOSSINESS — web-only information these conversions drop:",
    ...RN_LOSSINESS.map((n, i) => `//   ${i + 1}. ${n}`),
    "",
    "/** RN mapping of a DTCG shadow token (see header notes for the heuristics). */",
    "export interface DsRnShadow {",
    "  readonly shadowColor: string;",
    "  readonly shadowOffset: { readonly width: number; readonly height: number };",
    "  readonly shadowRadius: number;",
    "  readonly shadowOpacity: number;",
    "  readonly elevation: number;",
    "}",
    "",
    "/** Every public token (semantic + component tiers), keyed by DTCG path segments. */",
    "export const tokens = {",
    ...body,
    "} as const;",
    "",
    "export type DsRnTokens = typeof tokens;",
    "",
  ].join("\n");
}

